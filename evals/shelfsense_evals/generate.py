"""Generate the synthetic seed dataset: rendered shelves with known truth, plus planner cases.

Deterministic for a given seed, so the committed dataset can be regenerated byte-for-byte
(the PNG encoder is Pillow's, so regenerate on the same Pillow major version).
"""

import random
from pathlib import Path
from uuid import UUID

from shelfsense_api.agents.vision import ExtractionSummary, SlotCompliance
from shelfsense_api.seed import SHELF_CATEGORIES, TENANTS
from shelfsense_api.synthetic import Scenario, planogram_context, render
from shelfsense_evals.dataset import (
    InventoryRow,
    PlannerCase,
    PlannerExpected,
    PlanogramCase,
    PlanogramSlotCase,
    VisionCase,
    VisionTruth,
    write_dataset,
)

INTRUDERS = (
    "Lucozade Boost 50cl",
    "Nasco Cornflakes 350g",
    "Viju Milk Drink 500ml",
    "Kellogg's Cornflakes 500g",
    "Big Cola 1L",
)

# Every seeded shelf: (tenant slug, store name, shelf label).
SHELVES: tuple[tuple[str, str, str], ...] = tuple(
    (tenant.slug, store_name, label)
    for tenant in TENANTS
    for store_name, _address, _lat, _lng, labels in tenant.stores
    for label in labels
)

# Planner cases need unit prices; take them from the catalogue by name.
PRICES: dict[str, int] = {}
for _tenant in TENANTS:
    from shelfsense_api.seed import CATALOGUE

    for _item in CATALOGUE:
        PRICES[_item.name] = _item.price_kobo


def _planogram_case(tenant_slug: str, store_name: str, shelf_label: str) -> PlanogramCase:
    ctx = planogram_context(tenant_slug, store_name, shelf_label)
    return PlanogramCase(
        store_name=ctx.store_name,
        shelf_label=ctx.shelf_label,
        version=ctx.planogram_version,
        slots=[
            PlanogramSlotCase(
                sku_id=s.sku_id,
                name=s.name,
                brand=s.brand,
                position=s.position,
                expected_facings=s.expected_facings,
                min_facings=s.min_facings,
            )
            for s in ctx.slots
        ],
    )


def _vision_case(index: int, rng: random.Random, photos_dir: Path, dataset_dir: Path) -> VisionCase:
    tenant_slug, store_name, shelf_label = SHELVES[index % len(SHELVES)]
    planogram = _planogram_case(tenant_slug, store_name, shelf_label)
    if not planogram.slots:
        raise ValueError(f"{store_name} / {shelf_label} has no planogram slots in the seed")
    profile = rng.choice(["full", "full", "one_out", "two_out", "many_out", "intruder", "sparse"])
    facings: dict[str, int] = {}
    for slot in planogram.slots:
        base = slot.expected_facings
        facings[slot.name] = max(0, base + rng.choice([-1, 0, 0, 1]))
    names = [s.name for s in planogram.slots]
    if profile == "one_out":
        facings[rng.choice(names)] = 0
    elif profile == "two_out":
        for name in rng.sample(names, k=min(2, len(names))):
            facings[name] = 0
    elif profile == "many_out":
        for name in rng.sample(names, k=min(max(3, len(names) // 2), len(names))):
            facings[name] = 0
    elif profile == "sparse":
        for name in names:
            facings[name] = rng.choice([0, 1, 1, 2])
    unknown: tuple[str, ...] = ()
    if profile == "intruder" or rng.random() < 0.15:
        unknown = tuple(rng.sample(INTRUDERS, k=rng.choice([1, 1, 2])))
    scenario = Scenario(
        name=f"syn_{index:03d}",
        tenant_slug=tenant_slug,
        store_name=store_name,
        shelf_label=shelf_label,
        facings=facings,
        unknown_products=unknown,
        description=profile,
    )
    png, truth = render(scenario)
    photos_dir.mkdir(parents=True, exist_ok=True)
    image_path = photos_dir / f"{scenario.name}.png"
    image_path.write_bytes(png)
    sku_ids = truth["sku_ids"]
    assert isinstance(sku_ids, dict)
    facings_truth = truth["facings"]
    assert isinstance(facings_truth, dict)
    tags = [profile, shelf_label.lower().replace(" ", "_"), tenant_slug]
    if unknown:
        tags.append("intruder")
    stock_outs = [n for n, f in facings_truth.items() if f == 0]
    if len(stock_outs) >= 2:
        tags.append("multi_stockout")
    return VisionCase(
        id=scenario.name,
        source="synthetic",
        tags=sorted(set(tags)),
        image=str(image_path.relative_to(dataset_dir)),
        planogram=planogram,
        truth=VisionTruth(
            facings={UUID(sku_ids[name]): int(facings_truth[name]) for name in names},
            unknown_products=list(unknown),
        ),
        notes=profile,
    )


def _expected_decisions(
    summary: ExtractionSummary,
    inventory: list[InventoryRow],
    confidence: float,
    telemetry_fault: bool,
) -> PlannerExpected:
    """The policy the planner prompt describes, written down as code.

    Mirrors ``agents.planner.SYSTEM_PROMPT`` rule by rule: reorder what is out or low and
    at or below the reorder point; a shelf that can be refilled from the back room is a
    notification, not an order; notify on two or more stock-outs, low confidence or a
    fault; dispatch only on a fault; escalate when the audit cannot be trusted or when
    there is an equipment fault a human must look at.
    """
    on_hand = {row.sku_id: row for row in inventory}
    reorder: set[UUID] = set()
    refill_needed = False
    for slot in summary.slots:
        row = on_hand.get(slot.sku_id)
        if slot.status not in ("out", "low") or row is None:
            continue
        if row.on_hand <= row.reorder_point:
            reorder.add(slot.sku_id)
        else:
            refill_needed = True
    escalate = confidence < 0.5 or telemetry_fault
    notify = summary.stock_out_count >= 2 or confidence < 0.7 or telemetry_fault or refill_needed
    return PlannerExpected(
        reorder_skus=[] if confidence < 0.5 else sorted(reorder),
        notify=notify,
        dispatch=telemetry_fault,
        escalate=escalate,
    )


def _planner_case(index: int, rng: random.Random) -> PlannerCase:
    tenant_slug, store_name, shelf_label = SHELVES[index % len(SHELVES)]
    planogram = _planogram_case(tenant_slug, store_name, shelf_label)
    profile = rng.choice(["refill", "reorder", "reorder", "multi", "low_conf", "fault", "quiet"])
    confidence = {"low_conf": rng.uniform(0.3, 0.49)}.get(profile, rng.uniform(0.72, 0.95))
    slots: list[SlotCompliance] = []
    inventory: list[InventoryRow] = []
    outs = 0
    for slot in planogram.slots:
        observed = slot.expected_facings
        first_out = profile in ("reorder", "refill") and outs == 0 and rng.random() < 0.6
        multi_out = profile == "multi" and rng.random() < 0.45
        if first_out or multi_out:
            observed = 0
        elif rng.random() < 0.1:
            observed = max(0, slot.min_facings - 1)
        status = "out" if observed == 0 else ("low" if observed < slot.min_facings else "ok")
        outs += status == "out"
        slots.append(
            SlotCompliance(
                sku_id=slot.sku_id,
                name=slot.name,
                position=slot.position,
                expected_facings=slot.expected_facings,
                min_facings=slot.min_facings,
                observed_facings=observed,
                status=status,
            )
        )
        # Refill profile: plenty in the back room; reorder profile: at or below the point.
        if profile == "refill":
            on_hand = rng.randint(10, 24)
        elif profile in ("reorder", "multi"):
            on_hand = rng.randint(0, 6) if status != "ok" else rng.randint(4, 20)
        else:
            on_hand = rng.randint(2, 20)
        inventory.append(
            InventoryRow(
                sku_id=slot.sku_id,
                name=slot.name,
                on_hand=on_hand,
                reorder_point=6,
                case_size=12,
                unit_price_kobo=PRICES.get(slot.name, 50_000),
            )
        )
    n = len(slots) or 1
    summary = ExtractionSummary(
        slots=slots,
        stock_out_count=outs,
        stock_out_rate=outs / n,
        compliance_rate=sum(1 for s in slots if s.status == "ok") / n,
        planogram_share_of_shelf=100.0,
        unknown_item_count=0,
    )
    fault = profile == "fault"
    telemetry = (
        f"Fridge at {store_name} has been above 8°C for 40 minutes (peak 11.2°C)."
        if fault
        else None
    )
    expected = _expected_decisions(summary, inventory, confidence, fault)
    return PlannerCase(
        id=f"plan_{index:03d}",
        source="synthetic",
        tags=sorted({profile, tenant_slug}),
        store_name=store_name,
        shelf_label=shelf_label,
        trigger_role="manager",
        summary=summary,
        overall_confidence=round(confidence, 2),
        notes=profile,
        telemetry=telemetry,
        inventory=inventory,
        expected=expected,
    )


def generate(dataset_path: Path, *, vision: int = 60, planner: int = 40, seed: int = 2026) -> int:
    """Write the dataset and its photos. Returns the number of cases."""
    rng = random.Random(seed)
    dataset_dir = dataset_path.parent
    photos_dir = dataset_dir / "photos"
    cases: list[VisionCase | PlannerCase] = []
    for i in range(vision):
        cases.append(_vision_case(i, rng, photos_dir, dataset_dir))
    for i in range(planner):
        cases.append(_planner_case(i, rng))
    write_dataset(dataset_path, cases)
    return len(cases)


__all__ = ["SHELF_CATEGORIES", "generate"]
